// ご利用ガイドに書いてあることが、実際の画面と合っているかを確かめる。
//
// なぜ必要か:
//   説明が実物とずれていると、税理士は書いてあるとおりに操作して見つからず、
//   「壊れている」と判断してしまう。**間違った説明は不具合と同じ**。
//   実際、ガイドが Phase 3 のまま1年分古くなっていた（2026-08-05に発覚）。
//
//   ここでは「ガイドに出てくる画面の言葉」が、tax-workspace.html / pages に
//   本当に存在するかを1つずつ突き合わせる。
//
// 実行: node tools/test-guide-matches-app.js
'use strict';

const fs = require('fs');
const path = require('path');
const R = (...p) => fs.readFileSync(path.join(__dirname, '..', ...p), 'utf8');
const guide = R('tax-guide.html');
const html = R('tax-workspace.html');
const ui = R('pages', 'tax-workspace.js');
const app = html + '\n' + ui;      // 画面に出る文字はこの2つのどちらかにある

let ng = 0;
function ck(label, ok, detail) {
  if (!ok) ng++;
  console.log((ok ? '  ○ ' : '  × ') + label + (ok || !detail ? '' : '  → ' + detail));
}

/* ガイドが「画面にこう出ます」と書いている言葉。
 * 実物に無ければ、ガイドか実装のどちらかが古い。 */
console.log('===== ガイドが名指ししている画面の言葉が実在するか =====');
[
  ['タブ: ① 未仕訳の明細', '① 未仕訳の明細'],
  ['タブ: ② 仕訳待ちの証憑', '② 仕訳待ちの証憑'],
  ['タブ: ③ 共有ファイル', '③ 共有ファイル'],
  ['タブ: ④ 操作履歴', '④ 操作履歴'],
  ['タブ: ⑤ 月次チェック', '⑤ 月次チェック'],
  ['タブ: ⑥ 承認待ち', '⑥ 承認待ち'],
  ['ボタン: 仕訳を選んで添付', '仕訳を選んで添付'],
  ['ボタン: この仕訳に添付', 'この仕訳に添付'],
  ['表示: 証憑あり', '証憑あり'],
  ['ボタン: 確認を記録する', '確認を記録する'],
  ['⑤の区分: ① いつもあるのに今月まだ無い科目', '① いつもあるのに今月まだ無い科目'],
  ['⑤の区分: ② 金額が普段と大きく違う科目', '② 金額が普段と大きく違う科目'],
  ['⑤の区分: ③ 符号がおかしい科目', '③ 符号がおかしい科目'],
  ['⑤の区分: ④ 貸借対照表の確認', '④ 貸借対照表の確認'],
  ['⑤の区分: ⑤ 事業区分別の課税売上高', '⑤ 事業区分別の課税売上高'],
  ['ログイン画面のボタン: 新規登録', '新規登録'],
  ['ログイン画面のボタン: ログイン', 'ログイン'],
].forEach(([label, word]) => {
  // ガイドがその言葉を使っていること、かつ実物にもあること
  const inGuide = guide.indexOf(word) >= 0;
  const inApp = app.indexOf(word) >= 0;
  ck(label, inGuide && inApp,
    !inGuide ? 'ガイドに無い' : '実際の画面に無い（ガイドが古いか、実装が変わった）');
});

/* ①の既定の見た目。ガイドの図はカードなので、
 * 「はじめは一覧表示」と書いていないと、開いた瞬間に図と違って見える。 */
console.log('\n===== ①の既定の見た目とガイドの図が食い違っていないか =====');
const defaultView = /var txwUnmatchedView = '(\w+)'/.exec(ui);
ck('既定の表示を実装から読めた（' + (defaultView && defaultView[1]) + '）', !!defaultView);
if (defaultView && defaultView[1] === 'list') {
  ck('ガイドに「はじめは一覧表示」と書いてある', /はじめは一覧表示です/.test(guide));
  ck('ガイドの図がカードであることを断ってある', /下の図は<b>カード表示<\/b>の例です/.test(guide));
}

/* 「証憑を消せるのは社内だけ」など、運用の約束が両方に書いてあること */
console.log('\n===== 運用の約束が両方に書いてあるか =====');
[
  ['証憑をMFへ送ると取り消せない', /証憑をMFへ送ると、取り消せません/, /証憑をMFへ送ると、取り消せません|MFへ送った証憑は取り消せません/],
  ['仕訳の取り消しはMFの仕訳帳から', /MFクラウド会計の仕訳帳から削除|MFの仕訳帳から削除/, /MFの仕訳帳から削除/],
  ['②の証憑はこの画面から消せない', /RIBRE担当者までご連絡ください|RIBREへご連絡ください/, /ここから証憑を消すことはできません/],
  ['すでに証憑がある仕訳には足せない', /証憑あり/, /すでに証憑が付いています|証憑あり/],
].forEach(([label, gre, are]) => {
  ck(label, gre.test(guide) && are.test(app),
    !gre.test(guide) ? 'ガイドに無い' : '画面に無い');
});

/* 使い方タブの読み込み先が実在するファイルであること */
console.log('\n===== 使い方タブの読み込み =====');
const src = /<iframe[^>]*src="([^"]+)"/.exec(html);
ck('読み込み先が書いてある', !!src);
if (src) {
  ck('読み込み先のファイルが実在する（' + src[1] + '）',
    fs.existsSync(path.join(__dirname, '..', src[1])));
  /* ⚠ この枠は display:none のタブの中にある。遅延読み込みにすると
   *   タブを開いても空のままになることがある。 */
  ck('遅延読み込み(loading="lazy")を付けていない',
    !/<iframe[^>]*loading="lazy"/.test(html));
}
/* ガイドの中のリンクが、枠の中で外へ飛ばないこと（飛ぶと迷子になる） */
const links = [...guide.matchAll(/<a [^>]*href="([^"]+)"/g)].map((m) => m[1]);
const outer = links.filter((u) => !/^#/.test(u));
ck('ガイド内のリンクはページ内の移動だけ（' + (outer.join(', ') || 'なし') + '）',
  outer.length === 0);

console.log('\n===== 結果 =====');
console.log(ng === 0 ? '全件 期待どおり ○' : (ng + '件 期待とちがう ×'));
process.exit(ng === 0 ? 0 : 1);
